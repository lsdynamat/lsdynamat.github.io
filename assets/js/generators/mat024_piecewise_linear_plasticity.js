export function generate(input = {}) {
  const inp = { ...DEFAULTS, ...normalizeInput(input) };

  const mid = mustIntPositive("mid", inp.mid);
  const ro = mustNonNeg("ro", inp.ro);
  const E = mustPositive("E", inp.E);
  const pr = mustInRange("pr", inp.pr, 0.0, 0.49);

  const fy = mustNonNeg("fy", inp.fy);
  const fu = mustNonNeg("fu", inp.fu);
  if (fu < fy) throw new Error("fu must be >= fy");

  const n_plateau = mustIntMin("n_plateau", inp.n_plateau, 3);
  const n_hardening = mustIntMin("n_hardening", inp.n_hardening, 10);
  const tail_d_epsp = mustNonNeg("tail_d_epsp", inp.tail_d_epsp);
  const tail_h = mustNonNeg("tail_h", inp.tail_h);
  const zIn = readOptionalPositive(inp.z_pct);
  if (zIn != null && zIn >= 100) throw new Error("Z must be < 100 %");
  const h_el = mustPositive("h_el", inp.h_el);
  const damage = Math.round(mustInRange("damage", inp.damage, 0, 1));

  // ---------------- Yun & Gardner (engineering strains) ----------------
  const eps_y = fy / E;

  const eps_sh_formula = 0.1 * (fy / fu) - 0.055;
  let eps_sh = clamp(eps_sh_formula, 0.015, 0.03);

  const eps_u_formula = 0.6 * (1.0 - fy / fu);
  let eps_u = Math.max(eps_u_formula, 0.06);

  if (eps_sh <= eps_y) eps_sh = eps_y + 1e-4;
  if (eps_u <= eps_sh) eps_u = eps_sh + 1e-3;

  // Elastic (internal points)
  let eps_el = linspace(0, eps_y, N_ELASTIC_INTERNAL).slice(0, -1);
  let sig_el = eps_el.map((e) => E * e);

  // Yield plateau (user points)
  let eps_pl = linspace(eps_y, eps_sh, n_plateau).slice(0, -1);
  let sig_pl = eps_pl.map(() => fy);

  // Hardening (user points)
  const eps_h = linspace(eps_sh, eps_u, n_hardening);
  const sig_h = eps_h.map((e) => {
    const C = (e - eps_sh) / (eps_u - eps_sh);
    const D = Math.pow(1 + 400 * Math.pow(C, 5), 0.2); // (1/5)
    return fy + (fu - fy) * (0.4 * C + (2 * C) / D);
  });

  const eng_eps = eps_el.concat(eps_pl, eps_h);
  const eng_sig = sig_el.concat(sig_pl, sig_h);

  // ---------------- True conversion ----------------
  const tru_eps = eng_eps.map((e) => Math.log1p(e));
  const tru_sig = eng_sig.map((s, i) => s * (1 + eng_eps[i]));

  // True plastic strain (for curve x-axis)
  let eps_p = tru_eps.map((e, i) => {
    const ep = e - tru_sig[i] / E;
    return ep < 0 ? 0 : ep;
  });

  // Start at yield
  let i0 = eng_sig.findIndex((s) => s >= fy);
  if (i0 < 0) i0 = 0;

  eps_p = eps_p.slice(i0);
  let sig_true = tru_sig.slice(i0);

  // Shift so first eps_p = 0
  const ep0 = eps_p[0] ?? 0.0;
  eps_p = eps_p.map((v, i) => (i === 0 ? 0.0 : v - ep0));

  // Enforce monotonic eps_p
  for (let i = 1; i < eps_p.length; i++) {
    if (eps_p[i] <= eps_p[i - 1]) eps_p[i] = eps_p[i - 1] + 1e-12;
  }

  // Peak stress
  let ipk = 0;
  for (let i = 1; i < sig_true.length; i++) if (sig_true[i] > sig_true[ipk]) ipk = i;
  const sig_pk = sig_true[ipk];

  // Keep only up to peak
  eps_p = eps_p.slice(0, ipk + 1);
  sig_true = sig_true.slice(0, ipk + 1);

  // Beyond A_g: straight line with slope tail_h · σ_true(A_g). tail_h = 1 is the Considère slope,
  // so the neck starts at A_g and then grows gradually; tail_h = 0 gives the old flat tail.
  if (tail_d_epsp > 0) {
    eps_p.push(eps_p[eps_p.length - 1] + tail_d_epsp);
    sig_true.push(sig_pk * (1 + tail_h * tail_d_epsp));
  } else {
    sig_true[sig_true.length - 1] = sig_pk;
  }

  // Ductile fracture: fracture strain from Z, scaled for the element size in the neck
  const useGissmo = zIn != null && damage === 1;
  const lnZ = zIn != null ? Math.log(1 / (1 - zIn / 100)) : null;
  const kFail = zIn != null && !useGissmo ? failFactor(h_el) : null;
  const failStrain = kFail != null ? kFail * lnZ : null;
  const eps0 = useGissmo ? failFactor(1.0, GISSMO_K) * lnZ : null;
  const epsAg = eps_p[ipk];

  // ---------------- Keyword output (order matters) ----------------
  const lcss = mid * 1000 + 24;

  const titleLine = `MAT_024 YunGardner fy=${toFixed(fy, 1)}MPa fu=${toFixed(fu, 1)}MPa`;
  const curveTitle = `LCSS_${lcss} fy=${toFixed(fy, 1)} fu=${toFixed(fu, 1)}`;

  const lines = [];

  // 1) KEYWORD + banner + header comments (like MAT_273 style)
  lines.push("*KEYWORD");
  MATERIAL_CARDS_BANNER.forEach((l) => lines.push(l));

  // Optional header comment block (keep consistent ordering)
  lines.push(UNITS_LINE);
  lines.push(MODEL_LINE);
  REF_LINES.forEach((l) => lines.push(l));
  lines.push(HUB_LINE);

  // 2) DEFINE_CURVE (must come BEFORE MAT so LCSS exists)
  lines.push("*DEFINE_CURVE_TITLE");
  lines.push(curveTitle);
  lines.push("$#    LCID      SIDR       SFA       SFO      OFFA      OFFO");
  lines.push(
    `${fmt10(lcss)}` +
      `${fmt10(0)}` +
      `${fmt10(1.0, 6)}` +
      `${fmt10(1.0, 6)}` +
      `${fmt10(0.0, 6)}` +
      `${fmt10(0.0, 6)}`
  );
  lines.push("$#                a               o");
  for (let i = 0; i < eps_p.length; i++) {
    lines.push(`${fmt20(eps_p[i], 8)}${fmt20(sig_true[i], 6)}`);
  }

  // 3) MAT_024 card (TITLE short, only fy/fu)
  lines.push("*MAT_PIECEWISE_LINEAR_PLASTICITY_TITLE");
  lines.push(titleLine);

  if (failStrain != null) {
    lines.push(`$ FAIL = ${toFixed(kFail, 3)} x ln(1/(1-Z)) = ${toFixed(failStrain, 3)} for Z = ${toFixed(zIn, 1)} % and ${toFixed(h_el, 2)} mm elements in the neck`);
    lines.push(`$ (calibrated with the post-A_g slope H = ${toFixed(tail_h, 2)} x sigma_true(A_g); valid for 8-node solids)`);
    if (failStrain <= epsAg) lines.push("$ WARNING: FAIL is below the plastic strain at A_g: elements erode before necking");
  } else if (useGissmo) {
    lines.push("$ FAIL left at 0: fracture is handled by *MAT_ADD_DAMAGE_GISSMO below.");
  } else {
    lines.push("$ FAIL left at 0: no fracture. Enter Z to add element erosion at ductile fracture.");
  }

  // Rate effect disabled: output C=P=0
  const fail = failStrain ?? 0.0;
  const tdel = 0.0;
  const c = 0.0;
  const p = 0.0;

  lines.push("$#     MID        RO         E        PR      SIGY      ETAN      FAIL      TDEL");
  lines.push(
    `${fmt10(mid)}` +
      `${fmt10(ro, 7)}` +
      `${fmt10(E, 1)}` +
      `${fmt10(pr, 6)}` +
      `${fmt10(fy, 6)}` +
      `${fmt10(0.0, 6)}` +
      `${fmt10(fail, 6)}` +
      `${fmt10(tdel, 6)}`
  );

  lines.push("$#       C        P      LCSS      LCSR        VP");
  lines.push(`${fmt10(c, 6)}${fmt10(p, 6)}${fmt10(lcss)}${fmt10(0)}${fmt10(0)}`);

  // Cards 3-4 are required by LS-DYNA even when LCSS is used (values ignored)
  lines.push("$#    EPS1      EPS2      EPS3      EPS4      EPS5      EPS6      EPS7      EPS8");
  lines.push(Array(8).fill(fmt10(0)).join(""));
  lines.push("$#     ES1       ES2       ES3       ES4       ES5       ES6       ES7       ES8");
  lines.push(Array(8).fill(fmt10(0)).join(""));

  // 4) GISSMO damage (optional)
  if (useGissmo) {
    const lcsdg = mid * 1000 + 25;
    const lcregd = mid * 1000 + 26;
    lines.push("*MAT_ADD_DAMAGE_GISSMO");
    lines.push(`$ Ductile fracture from Z = ${toFixed(zIn, 1)} %: eps_f(eta) = ${toFixed(eps0, 4)} x exp(-1.5 (eta - 1/3)) for 1 mm elements (Rice-Tracey)`);
    lines.push("$ LCREGD scales eps_f with the element size; ECRIT = plastic strain at A_g (onset of necking)");
    lines.push("$ Calibrated on BAM S355 flat tensile tests with 8-node solids and the post-A_g slope H = sigma_true(A_g)");
    lines.push("$      MID     blank      DTYP     REFSZ    NUMFIP");
    lines.push(`${fmt10(mid)}${" ".repeat(10)}${fmt10(1)}${fmt10(0.0, 1)}${fmt10(1.0, 1)}`);
    lines.push("$#   LCSDG     ECRIT    DMGEXP     DCRIT    FADEXP    LCREGD");
    lines.push(`${fmt10(lcsdg)}${fmt10(epsAg, 5)}${fmt10(GISSMO_DMGEXP, 1)}${fmt10(0.0, 1)}${fmt10(GISSMO_FADEXP, 1)}${fmt10(lcregd)}`);
    lines.push("$#   LCSRS      SHRF     BIAXF    LCDLIM   MIDFAIL     HISVN      SOFT     LP2BI");
    lines.push(`${fmt10(0)}${fmt10(0.0, 1)}${fmt10(0.0, 1)}${fmt10(0)}${fmt10(0.0, 1)}${fmt10(0)}${fmt10(0.0, 1)}${fmt10(0.0, 1)}`);

    lines.push("*DEFINE_CURVE_TITLE");
    lines.push(`GISSMO failure strain vs triaxiality, Z=${toFixed(zIn, 1)}%`);
    lines.push("$#    LCID      SIDR       SFA       SFO      OFFA      OFFO");
    lines.push(`${fmt10(lcsdg)}${fmt10(0)}${fmt10(1.0, 1)}${fmt10(1.0, 1)}${fmt10(0.0, 1)}${fmt10(0.0, 1)}`);
    lines.push("$#                a               o");
    // constant below eta = -1/3 (no void growth in compression), Rice-Tracey above
    const etas = [-1.0];
    for (let k = 0; k <= 23; k++) etas.push(-1 / 3 + 0.1 * k);
    for (const eta of etas) {
      const ef = eps0 * Math.exp(-1.5 * (Math.max(eta, -1 / 3) - 1 / 3));
      lines.push(`${fmt20(eta, 6)}${fmt20(ef, 6)}`);
    }

    lines.push("*DEFINE_CURVE_TITLE");
    lines.push("GISSMO regularisation factor vs element size");
    lines.push("$#    LCID      SIDR       SFA       SFO      OFFA      OFFO");
    lines.push(`${fmt10(lcregd)}${fmt10(0)}${fmt10(1.0, 1)}${fmt10(1.0, 1)}${fmt10(0.0, 1)}${fmt10(0.0, 1)}`);
    lines.push("$#                a               o");
    const k1 = failFactor(1.0, GISSMO_K);
    for (const h of [0.1, 0.5, 0.75, 1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 100.0]) {
      lines.push(`${fmt20(h, 4)}${fmt20(failFactor(h, GISSMO_K) / k1, 6)}`);
    }
  }

  // 5) END
  lines.push("*END");
  lines.push("");

  const filename = `MAT_024_YunGardner_mid=${mid}_fy=${toFixed(fy, 1)}_fu=${toFixed(fu, 1)}.k`;
  return { filename, keyword: lines.join("\n") };
}

// ---------------- helpers ----------------
function clamp(x, lo, hi) {
  return Math.max(lo, Math.min(hi, x));
}
function linspace(a, b, n) {
  if (n <= 1) return [a];
  const arr = new Array(n);
  const step = (b - a) / (n - 1);
  for (let i = 0; i < n; i++) arr[i] = a + step * i;
  return arr;
}
function normalizeInput(obj) {
  const out = { ...obj };
  for (const k of Object.keys(out)) if (out[k] === "") out[k] = "";
  return out;
}
function readOptionalPositive(x) {
  if (x === undefined || x === null) return null;
  const s = String(x).trim();
  if (s === "") return null;
  const v = Number(s);
  return Number.isFinite(v) && v > 0 ? v : null;
}
function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v) || v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustNonNeg(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v) || v < 0) throw new Error(`${name} must be >= 0`);
  return v;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustIntMin(name, x, min) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi < min) throw new Error(`${name} must be an integer >= ${min}`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v) || v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}
function toFixed(x, n) {
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x);
  return v.toFixed(n);
}
function fmt10(x, decimals = 6) {
  return fitW(fmt10Raw(x, decimals), x, 10);
}
function fmt10Raw(x, decimals = 6) {
  if (Number.isInteger(x)) return String(x).padStart(10, " ");
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");
  const av = Math.abs(v);
  if (av !== 0 && (av >= 1e6 || av < 1e-4)) return v.toExponential(3).replace("e", "E").padStart(10, " ");
  return v.toFixed(decimals).padStart(10, " ");
}
function fmt20(x, decimals = 6) {
  return fitW(fmt20Raw(x, decimals), x, 20);
}
function fmt20Raw(x, decimals = 6) {
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(20, " ");
  const av = Math.abs(v);
  if (av !== 0 && (av >= 1e8 || av < 1e-8)) return v.toExponential(6).replace("e", "E").padStart(20, " ");
  return v.toFixed(decimals).padStart(20, " ");
}

// Never let a number overflow its field or touch the previous one (LS-DYNA reads by column).
function fitW(s, v, w) {
  const n = Number(v);
  if (!Number.isFinite(n)) return s;
  if (s.length > w || (s.length === w && s[0] !== " ")) return " " + fitField(n, w - 1);
  return s;
}
