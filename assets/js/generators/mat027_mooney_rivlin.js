export const KEY = "mat027_mooney_rivlin";
export const ID = 27;
export const NAME = "Mooney–Rivlin Rubber (*MAT_MOONEY-RIVLIN_RUBBER)";
export const CATEGORY = "Rubber";
export const UNITS = "mm-ms-g-N-MPa";

// Dimension of every field written below (see core/units.js); the generator writes mm-ms-g-N-MPa.
export const UNIT_SPEC = {
  "*MAT_MOONEY-RIVLIN_RUBBER": { rows: [["-", "D", "-", "S", "S", "-"], ["L", "L", "L", "-"]] },
};

const HUB_LINE = "$ Generated by LS DYNA Material Hub https://lsdynamat.github.io/";
const UNITS_LINE = "$ Units: mm-ms-g-N-MPa";
const MODEL_LINE = "$ Model: Mooney-Rivlin rubber - *MAT_MOONEY-RIVLIN_RUBBER (MAT_027)";
const REF_LINES = ["$ Reference: LS-DYNA Keyword User's Manual - MAT_027"];

const MATERIAL_CARDS_BANNER = [
  "$ --+----1----+----2----+----3----+----4----+----5----+----6----+----7----+----8",
  "$                                                                              $",
  "$                                MATERIAL CARDS                                $",
  "$                                                                              $",
  "$ --+----1----+----2----+----3----+----4----+----5----+----6----+----7----+----8",
];

export const DEFAULTS = {
  mid: 27,
  ro: 0.0011,
  pr: 0.495,
  c10: 0.5,
  c01: 0.2,
};

export function generate(input = {}) {
  const inp = { ...DEFAULTS, ...input };

  const mid = mustIntPositive("mid", inp.mid);
  const ro  = mustPositive("ro", inp.ro);
  const pr  = mustInRange("pr", inp.pr, 0.49, 0.4999);
  const A   = mustNonNeg("c10", inp.c10);
  const B   = mustNonNeg("c01", inp.c01);
  if (A + B <= 0) throw new Error("C10 + C01 must be > 0");

  const G = 2 * (A + B);                               // small-strain shear modulus
  const K = (2 * G * (1 + pr)) / (3 * (1 - 2 * pr));   // implied bulk modulus

  const title = `MAT_027 Mooney-Rivlin C10=${toFixed(A, 3)} C01=${toFixed(B, 3)} MPa`;

  const lines = [];
  lines.push("$# LS-DYNA Keyword file created by LS-PrePost");
  lines.push("*KEYWORD");
  MATERIAL_CARDS_BANNER.forEach(s => lines.push(s));
  lines.push(UNITS_LINE);
  lines.push(MODEL_LINE);
  REF_LINES.forEach(s => lines.push(s));
  lines.push(HUB_LINE);
  lines.push(`$ Derived: G = 2(A+B) = ${toFixed(G, 4)} MPa, K = 2G(1+PR)/(3(1-2PR)) = ${toFixed(K, 1)} MPa`);
  lines.push("$ Card 2 left zero: A and B are used directly (no least-squares fit)");

  lines.push("*MAT_MOONEY-RIVLIN_RUBBER_TITLE");
  lines.push(title);
  lines.push("$#     mid        ro        pr         a         b       ref");
  lines.push(fmt10(mid) + fmt10(ro, 6) + fmt10(pr, 4) + fmt10(A, 5) + fmt10(B, 5) + fmt10(0.0, 1));
  lines.push("$#     sgl        sw        st      lcid");
  lines.push(fmt10(0.0, 1) + fmt10(0.0, 1) + fmt10(0.0, 1) + fmt10(0));

  lines.push("*END");
  lines.push("");

  const filename = `MAT_027_MOONEY_RIVLIN_mid=${mid}_C10=${toFixed(A, 3)}_C01=${toFixed(B, 3)}.k`;
  return { filename, keyword: lines.join("\n") };
}

// ---- helpers ----
function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustNonNeg(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < 0) throw new Error(`${name} must be >= 0`);
  return v;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}
function toFixed(x, n) {
  const v = Number(x);
  return Number.isFinite(v) ? v.toFixed(n) : String(x);
}
function fmt10(x, decimals = 6) {
  return fitW(fmt10Raw(x, decimals), x, 10);
}
function fmt10Raw(x, decimals = 6) {
  if (Number.isInteger(x) && Math.abs(x) < 1e9) return String(x).padStart(10, " ");
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");
  const av = Math.abs(v);
  if (av !== 0 && (av >= 1e6 || av < 1e-4)) {
    return v.toExponential(3).replace("e", "E").padStart(10, " ");
  }
  let s = v.toFixed(decimals);
  while (s.length > 10 && decimals > 0) s = v.toFixed(--decimals);
  return s.padStart(10, " ");
}

// Never let a number overflow its field or touch the previous one (LS-DYNA reads by column).
function fitW(s, v, w) {
  const n = Number(v);
  if (!Number.isFinite(n)) return s;
  if (s.length > w || (s.length === w && s[0] !== " ")) return " " + fitField(n, w - 1);
  return s;
}
