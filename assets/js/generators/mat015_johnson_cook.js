export const DEFAULTS = {
  mid: 15,
  ro: 0.00785,
  e: 210000,
  pr: 0.3,
  a: 350, b: 400, n: 0.35, c: 0.02, m: 1.0,
  troom: 293, tmelt: 1793,
  eps0: 1.0,     // 1/s (converted to 1/ms on output)
  cp: 452,       // J/(kg K) = mJ/(g K)
  pc: -1.0e20,   // no tensile cutoff
  vp: 0,
  d1: "", d2: "", d3: "", d4: "", d5: "",
};

export function generate(input = {}) {
  const inp = { ...DEFAULTS, ...input };

  const mid  = mustIntPositive("mid", inp.mid);
  const ro   = mustPositive("ro", inp.ro);
  const E    = mustPositive("e", inp.e);
  const pr   = mustInRange("pr", inp.pr, 0.0, 0.49);
  const A    = mustNonNeg("a", inp.a);
  const B    = mustNonNeg("b", inp.b);
  const n    = mustNonNeg("n", inp.n);
  const C    = mustNonNeg("c", inp.c);
  const m    = mustNonNeg("m", inp.m);
  const tr   = mustPositive("troom", inp.troom);
  const tm   = mustPositive("tmelt", inp.tmelt);
  if (tm <= tr) throw new Error("tmelt must be greater than troom");
  const eps0_s = mustPositive("eps0", inp.eps0);
  const cp   = mustPositive("cp", inp.cp);
  const pc   = Number(inp.pc);
  if (!Number.isFinite(pc) || pc > 0) throw new Error("pc must be <= 0 (tensile cutoff)");
  const vp   = Number(inp.vp) >= 0.5 ? 1 : 0;

  // Failure (Johnson–Cook damage): all blank => failure not used
  const D = ["d1", "d2", "d3", "d4", "d5"].map(k => readOptionalNumber(inp[k]));
  const useDamage = D.some(v => v !== null);
  const [d1, d2, d3, d4, d5] = D.map(v => v ?? 0);

  // Derived
  const G = E / (2 * (1 + pr));            // shear modulus (needed for solids)
  const K = E / (3 * (1 - 2 * pr));        // bulk modulus -> EOS C1
  const eps0 = eps0_s * 1.0e-3;            // 1/s -> 1/ms
  const eosid = mid;

  const title = `MAT_015 JC A=${toFixed(A, 0)} B=${toFixed(B, 0)} n=${toFixed(n, 3)} C=${toFixed(C, 4)}`;

  const lines = [];
  lines.push("$# LS-DYNA Keyword file created by LS-PrePost");
  lines.push("*KEYWORD");
  MATERIAL_CARDS_BANNER.forEach(s => lines.push(s));
  lines.push(UNITS_LINE);
  lines.push(MODEL_LINE);
  REF_LINES.forEach(s => lines.push(s));
  lines.push(HUB_LINE);
  lines.push(`$ Derived: G = E/(2(1+PR)) = ${toFixed(G, 1)} MPa, K = E/(3(1-2PR)) = ${toFixed(K, 1)} MPa`);
  lines.push(`$ EPS0 = ${eps0_s} 1/s = ${eps0} 1/ms`);
  lines.push("$ Solid elements need the EOS below: set EOSID on *PART to " + eosid);
  if (!useDamage) lines.push("$ D1-D5 left blank: EROD=1, elements do not erode (no JC failure)");

  lines.push("*MAT_JOHNSON_COOK_TITLE");
  lines.push(title);
  lines.push("$#     mid        ro         g         e        pr       dtf        vp    rateop");
  lines.push(
    fmt10(mid) + fmt10(ro, 5) + fmt10(G, 1) + fmt10(E, 1) + fmt10(pr, 3) +
    fmt10(0.0, 1) + fmt10(vp, 1) + fmt10(0.0, 1)
  );
  lines.push("$#       a         b         n         c         m        tm        tr      eps0");
  lines.push(
    fmt10(A, 3) + fmt10(B, 3) + fmt10(n, 4) + fmt10(C, 5) + fmt10(m, 4) +
    fmt10(tm, 1) + fmt10(tr, 1) + fmt10(eps0, 6)
  );
  lines.push("$#      cp        pc     spall        it        d1        d2        d3        d4");
  lines.push(
    fmt10(cp, 2) + fmt10(pc, 1) + fmt10(2.0, 1) + fmt10(0.0, 1) +
    fmt10(d1, 4) + fmt10(d2, 4) + fmt10(d3, 4) + fmt10(d4, 4)
  );
  lines.push("$#      d5              erod     efmin    numint");
  lines.push(
    fmt10(d5, 4) + " ".repeat(10) + fmt10(useDamage ? 0.0 : 1.0, 1) + fmt10(1.0e-6) + fmt10(0)
  );

  lines.push("*EOS_LINEAR_POLYNOMIAL_TITLE");
  lines.push(`Linear EOS for MAT_015 mid=${mid} (C1 = bulk modulus)`);
  lines.push("$#   eosid        c0        c1        c2        c3        c4        c5        c6");
  lines.push(fmt10(eosid) + fmt10(0.0, 1) + fmt10(K, 1) + [0, 0, 0, 0, 0].map(() => fmt10(0.0, 1)).join(""));
  lines.push("$#      e0        v0");
  lines.push(fmt10(0.0, 1) + fmt10(1.0, 1));

  lines.push("*END");
  lines.push("");

  const filename = `MAT_015_JOHNSON_COOK_mid=${mid}_A=${toFixed(A, 0)}MPa.k`;
  return { filename, keyword: lines.join("\n") };
}

// ---- helpers ----
function readOptionalNumber(x) {
  if (x === undefined || x === null) return null;
  const s = String(x).trim();
  if (s === "") return null;
  const v = Number(s);
  return Number.isFinite(v) ? v : null;
}
function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustNonNeg(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < 0) throw new Error(`${name} must be >= 0`);
  return v;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}
function toFixed(x, n) {
  const v = Number(x);
  return Number.isFinite(v) ? v.toFixed(n) : String(x);
}
// 10-character fixed-format field
function fmt10(x, decimals = 6) {
  return fitW(fmt10Raw(x, decimals), x, 10);
}
function fmt10Raw(x, decimals = 6) {
  if (Number.isInteger(x) && Math.abs(x) < 1e9) return String(x).padStart(10, " ");
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");
  const av = Math.abs(v);
  if (av !== 0 && (av >= 1e6 || av < 1e-4)) {
    return v.toExponential(3).replace("e", "E").padStart(10, " ");
  }
  let s = v.toFixed(decimals);
  while (s.length > 10 && decimals > 0) s = v.toFixed(--decimals);
  return s.padStart(10, " ");
}

// Never let a number overflow its field or touch the previous one (LS-DYNA reads by column).
function fitW(s, v, w) {
  const n = Number(v);
  if (!Number.isFinite(n)) return s;
  if (s.length > w || (s.length === w && s[0] !== " ")) return " " + fitField(n, w - 1);
  return s;
}
