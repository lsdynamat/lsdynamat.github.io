// Ottosen failure surface with the Winfrith constants (Schwer 2011, Eq. 1-2, 8-12): compressive and tensile
// meridians; linear crack softening to the crack width FE written with RATE = 1 (Schwer 2011, p. 16);
// built-in pressure-volume curve (Schwer 2011, Table 1, multiples of Pc = f_c/3).
export function figures(input = {}) {
  const inp = { ...DEFAULTS, ...normalizeInput(input) };
  const fc = Number(inp.fc), dmax = Number(inp.dmax), pr = Number(inp.pr);
  if (!(fc > 0) || !(dmax > 0) || !(pr >= 0 && pr < 0.5)) return [];
  const tm = calculate_tm(fc), uts = calculate_ft(fc), fe = calculate_wc(fc, dmax);
  const R = uts / fc, al = 1.16, be = 0.5907445, ga = -0.6123724;
  const b = (1 + R * al * ga / 3 - al * al * ga / 3 - al / R) / (al * al * be / 3 - 3 * al - R * al * be / 3);
  const a = be * b + ga;
  const c = Math.sqrt(3) / R * (1 - b * R - R * R * a / 3);
  const d = (3 + 3 * b - a) / Math.sqrt(3);
  const k2 = Math.cos(3 * Math.atan(1 / Math.sqrt(3) - 2 * d / (c * Math.sqrt(3))));
  const k1 = c / Math.cos(Math.acos(k2) / 3);
  const lamT = k1 * Math.cos(Math.acos(k2) / 3), lamC = k1 * Math.cos(Math.PI / 3 - Math.acos(k2) / 3);
  const apex = -fc / (3 * b);
  const mer = lam => { const o = []; for (let i = 0; i <= 160; i++) {
    const P = apex + (3 * fc - apex) * (i / 160) ** 1.5, I1 = -3 * P;
    const s = fc * (-lam + Math.sqrt(Math.max(0, lam * lam - 4 * a * (b * I1 / fc - 1)))) / (2 * a);
    o.push([P, Math.sqrt(3) * s]); } return o; };
  const out = [{
    title: "Ottosen failure surface (meridians)", inputs: ["fc"],
    series: [{ label: "compressive meridian", slot: 1, points: mer(lamC) }, { label: "tensile meridian", slot: 4, points: mer(lamT), dash: true }],
    marks: [{ x: fc / 3, y: fc, label: "f_c", slot: 9 }, { x: -uts / 3, y: uts, label: `f_t ${uts.toFixed(2)}`, slot: 9 }],
    xMin: apex, xLabel: "pressure (MPa)", yLabel: "√(3 J2) (MPa)",
    caption: `Four-parameter surface through f_c, f_t and the biaxial strength 1.16 f_c; apex at p = ${apex.toFixed(2)} MPa.`,
  }];
  out.push({
    title: "Crack softening (RATE = 1)", inputs: ["fc", "dmax"],
    series: [{ label: "crack-normal stress", slot: 4, points: [[0, uts], [fe, 0], [fe * 1.2, 0]], legend: false }],
    marks: [{ x: fe, y: 0, label: `FE = ${fe.toFixed(3)} mm`, slot: 9 }],
    xLabel: "crack opening (mm)", yLabel: "stress (MPa)",
    caption: `Linear from UTS = ${uts.toFixed(2)} MPa to zero at FE; area = G_F = ${(uts * fe / 2 * 1000).toFixed(0)} N/m.`,
  });
  const K = tm / (3 * (1 - 2 * pr)), Pc = fc / 3;
  const tab = [[Pc / K, 1], [0.002, 1.5], [0.004, 3], [0.010, 4.8], [0.020, 6], [0.030, 7.5], [0.041, 9.45], [0.051, 11.55], [0.062, 14.25], [0.094, 25.05]];
  out.push({
    title: "Pressure–volume curve (built in)", inputs: ["fc", "pr"],
    series: [{ label: "pressure", slot: 2, points: [[0, 0], ...tab.map(([e, f]) => [e, f * Pc])], legend: false }],
    xLabel: "volumetric strain, compression (–)", yLabel: "pressure (MPa)",
    caption: "Generated by LS-DYNA when the EPS/P pairs are left zero (first point P_c = f_c/3 at P_c/K).",
  });
  return out;
}
