function normalizeInput(obj) {
  const out = { ...obj };
  for (const k of Object.keys(out)) {
    if (out[k] === "") out[k] = undefined;
  }
  return out;
}

function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}

// Fixed width column formatting (10 chars)
function f10i(x) {
  return fitW(f10iRaw(x), x, 10);
}
function f10iRaw(x) {
  return String(Math.trunc(Number(x))).padStart(10, " ");
}
function f10(x, decimals = 6, trim = false) {
  return fitW(f10Raw(x, decimals, trim), x, 10);
}
function f10Raw(x, decimals = 6, trim = false) {
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");
  let s = v.toFixed(decimals);
  if (trim) {
    // keep at least one decimal if decimals>0
    // but do NOT remove decimals aggressively (LS-PrePost look)
    // We keep exact toFixed
  }
  return s.padStart(10, " ");
}

// Scientific formatting like "6.11000E-4" and ALWAYS 5 decimals in mantissa
function f10sci(x, mantissaDecimals = 5) {
  return fitW(f10sciRaw(x, mantissaDecimals), x, 10);
}
function f10sciRaw(x, mantissaDecimals = 5) {
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");

  // Build mantissa/exponent manually to control decimals + exponent sign format
  if (v === 0) return ("0.00000E+0").padStart(10, " "); // rare

  const exp = Math.floor(Math.log10(Math.abs(v)));
  const m = v / Math.pow(10, exp);

  // exponent in LS-PrePost often like E-4 (no leading zero)
  const mantissa = m.toFixed(mantissaDecimals);
  const eSign = exp >= 0 ? "+" : "-";
  const eAbs = Math.abs(exp).toString(); // no leading zeros

  // Example: 6.11000E-4
  const s = `${mantissa}E${eSign}${eAbs}`;
  return s.padStart(10, " ");
}

function formatCreatedNow() {
  // Example wanted: Dec-27-2025 (08:26:24)
  const d = new Date();
  const mon = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"][d.getMonth()];
  const day = String(d.getDate()).padStart(2, "0");
  const year = d.getFullYear();
  const hh = String(d.getHours()).padStart(2, "0");
  const mm = String(d.getMinutes()).padStart(2, "0");
  const ss = String(d.getSeconds()).padStart(2, "0");
  return `${mon}-${day}-${year} (${hh}:${mm}:${ss})`;
}

/* =========================
   Ported Python math (1:1)
   ========================= */

function calculateFractureEnergy(fc, dmax = 16) {
  // fc is the measured (mean) cylinder strength, so fcm = fc (CEB-FIP MC90 G_F)
  const fcm = fc;
  const fcm0 = 10;          // MPa

  const GF0 = 0.021 + 5.357e-4 * dmax;
  const GF = GF0 * Math.pow(fcm / fcm0, 0.7);

  return { GF0, GF };
}

function calculateModulus(fc, poisson_ratio = 0.2) {
  const Ec0 = 21.5e3;
  const fcm = fc;           // measured (mean) cylinder strength
  const fcm0 = 10;

  // CEB-FIP MC90 tangent modulus (the Python port added 8 MPa twice: fc + 16)
  const E = Ec0 * Math.pow(fcm / fcm0, 1 / 3);

  const G = E / (2 * (1 + poisson_ratio));
  const K = E / (3 * (1 - 2 * poisson_ratio));
  return { G, K };
}

function calculateAlphaBeta(fc) {
  const alpha = 13.9846 * Math.exp(fc / 68.8756) - 13.8981;
  const theta = 0.3533 - 3.3294e-4 * fc - 3.8182e-6 * (fc ** 2);
  const lamda = 3.6657 * Math.exp(fc / 39.9363) - 4.7092;
  const beta = 18.17791 * (fc ** -1.7163);

  const alpha1 = 0.82;
  const theta1 = 0.0;
  const lamda1 = 0.24;
  const beta1 = 0.33565 * (fc ** -0.95383);

  const alpha2 = 0.76;
  const theta2 = 0.0;
  const lamda2 = 0.26;
  const beta2 = 0.285 * (fc ** -0.94843);

  return { alpha, theta, lamda, beta, alpha1, theta1, lamda1, beta1, alpha2, theta2, lamda2, beta2 };
}

function calculateAdditionalParameters(fc) {
  const fpsi = fc * 145.038;

  // Murray (2007) fits, f'c in psi, time in seconds: eta = eta0 / rate^n
  const nc = 0.78;
  const nt = 0.48;
  const eta0c_s = 1.2772337e-11 * (fpsi ** 2) - 1.0613722e-7 * fpsi + 3.203497e-4;
  const eta0t_s = 8.0614774e-13 * (fpsi ** 2) - 9.77736719e-10 * fpsi + 5.0752351e-5;
  // s -> ms: eta0 carries units s^(1-n), so multiply by 1000^(1-n)
  // (matches the values *MAT_CSCM_CONCRETE generates internally with UNITS = 1)
  const eta0c = eta0c_s * Math.pow(1000, 1 - nc);
  const eta0t = eta0t_s * Math.pow(1000, 1 - nt);

  const overc = 1.309663e-2 * (fc ** 2) - 0.3927659 * fc + 21.45;
  const overt = 1.309663e-2 * (fc ** 2) - 0.3927659 * fc + 21.45;

  const srate = 1.0;
  const repow = 1.0;

  return { eta0c, nc, eta0t, nt, overc, overt, srate, repow };
}

function calculateRXd(fc) {
  const R = 4.45994 * Math.exp(-fc / 11.51679) + 1.95358;
  const XD = 17.087 + 1.892 * fc;
  return { R, XD };
}

// Never let a number overflow its field or touch the previous one (LS-DYNA reads by column).
function fitW(s, v, w) {
  const n = Number(v);
  if (!Number.isFinite(n)) return s;
  if (s.length > w || (s.length === w && s[0] !== " ")) return " " + fitField(n, w - 1);
  return s;
}

// ----------------------- figures (generator page) -----------------------
// Same parameters as the card. Equations from Murray 2007 (FHWA-HRT-05-062): shear surface
// Ff = alpha - lamda exp(-beta J1) + theta J1, Rubin factors Q1 (TOR), Q2 (TXE), equal to 0.5774 and 0.5
// for J1 < 0; cap Fc = 1 - ((J1 - L)/(X - L))^2 for J1 > L, X = L + R Ff(L); hardening
// eps_v^p = W (1 - exp(-D1 (X - X0) - D2 (X - X0)^2)); rate eta = eta0 / rate^n, overstress capped.
const logTick = v => Number.isInteger(v) ? `1e${v}` : Math.pow(10, v).toExponential(1);

export function figures(input = {}) {
  const inp = { ...DEFAULTS, ...normalizeInput(input) };
  const fc = Number(inp.fc), pr = Number(inp.pr);
  if (!(fc > 0) || !(pr >= 0 && pr < 0.5)) return [];
  const { G, K } = calculateModulus(fc, pr);
  const ab = calculateAlphaBeta(fc), rx = calculateRXd(fc), add = calculateAdditionalParameters(fc);
  const W = 0.065, D1 = 0.000611, D2 = 0.000002;
  const Ff = J1 => ab.alpha - ab.lamda * Math.exp(-ab.beta * J1) + ab.theta * J1;
  const Q1 = J1 => J1 < 0 ? 0.5774 : ab.alpha1 - ab.lamda1 * Math.exp(-ab.beta1 * J1) + ab.theta1 * J1;
  const Q2 = J1 => J1 < 0 ? 0.5 : ab.alpha2 - ab.lamda2 * Math.exp(-ab.beta2 * J1) + ab.theta2 * J1;
  // initial cap: L0 with L0 + R Ff(L0) = X0 (bisection)
  let lo = 0, hi = rx.XD;
  for (let k = 0; k < 80; k++) { const m = (lo + hi) / 2; (m + rx.R * Ff(m) < rx.XD ? lo = m : hi = m); }
  const L0 = (lo + hi) / 2;
  const Fc = J1 => J1 <= L0 ? 1 : Math.max(0, 1 - ((J1 - L0) / (rx.XD - L0)) ** 2);
  // uniaxial tension on the TXE meridian: sigma = sqrt3 Q2 Ff at J1 = -sigma
  let a = 0, b = fc;
  for (let k = 0; k < 80; k++) { const m = (a + b) / 2; (Math.sqrt(3) * 0.5 * Ff(-m) > m ? a = m : b = m); }
  const ft = (a + b) / 2;
  let jt = -fc, jh = 0;                                  // tensile end of the shear surface: Ff = 0
  for (let k = 0; k < 80; k++) { const m = (jt + jh) / 2; (Ff(m) > 0 ? jh = m : jt = m); }
  const J1min = Math.max(jh, -3 * ft * 1.5);
  const S3 = Math.sqrt(3), pts = (f, J1max) => {
    const o = []; for (let i = 0; i <= 160; i++) { const J1 = J1min + (J1max - J1min) * i / 160; o.push([J1 / 3, Math.max(0, f(J1))]); } return o; };
  const Jtop = rx.XD * 1.6;
  const out = [{
    title: "Shear surface and initial cap", inputs: ["fc"],
    series: [
      { label: "compressive meridian (TXC)", slot: 1, points: pts(J => S3 * Ff(J), Jtop) },
      { label: "torsion (TOR)", slot: 5, points: pts(J => S3 * Q1(J) * Ff(J), Jtop), dash: true },
      { label: "tensile meridian (TXE)", slot: 4, points: pts(J => S3 * Q2(J) * Ff(J), Jtop), dash: true },
      { label: "TXC with initial cap", slot: 2, points: pts(J => S3 * Ff(J) * Math.sqrt(Fc(J)), rx.XD) },
    ],
    marks: [{ x: fc / 3, y: fc, label: "f_c", slot: 6 }, { x: -ft / 3, y: ft, label: `f_t ${ft.toFixed(2)}`, slot: 6 }],
    xMin: J1min / 3, xLabel: "pressure J1/3 (MPa)", yLabel: "√(3 J2) (MPa)",
    caption: `Cap starts at J1 = L0 = ${L0.toFixed(1)} MPa and meets the J1 axis at X0 = ${rx.XD.toFixed(1)} MPa (R = ${rx.R.toFixed(3)}).`,
  }];
  const hyd = [[0, 0]];
  for (let i = 0; i <= 60; i++) {
    const X = rx.XD * (1 + 40 * (i / 60) ** 2), dX = X - rx.XD;
    hyd.push([X / (3 * K) + W * (1 - Math.exp(-D1 * dX - D2 * dX * dX)), X / 3]);
  }
  out.push({
    title: "Hydrostatic compression (cap hardening)", inputs: ["fc", "pr"],
    series: [{ label: "pressure", slot: 2, points: hyd, legend: false }],
    marks: [{ x: rx.XD / (3 * K), y: rx.XD / 3, label: "X0/3", slot: 4 }],
    xLabel: "volumetric strain (–)", yLabel: "pressure (MPa)",
    caption: `Elastic with K = ${K.toFixed(0)} MPa up to X0/3, then plastic compaction towards W = ${W}.`,
  });
  if (Number(inp.irate) === 1) {
    const E = 9 * K * G / (3 * K + G), C = [], T = [];
    for (let i = 0; i <= 70; i++) {
      const lg = -4 + 7 * i / 70, r = 10 ** lg / 1000;          // 1/s -> 1/ms (card units)
      C.push([lg, 1 + Math.min(E * r * add.eta0c / r ** add.nc, add.overc) / fc]);
      T.push([lg, 1 + Math.min(E * r * add.eta0t / r ** add.nt, add.overt) / ft]);
    }
    out.push({
      title: "Strain-rate enhancement", inputs: ["fc", "irate"],
      series: [{ label: "compression", slot: 2, points: C }, { label: "tension", slot: 4, points: T }],
      xMin: -4, xMax: 3, yMin: 1, xTick: logTick, xLabel: "strain rate (1/s)", yLabel: "DIF",
      caption: `1 + E rate η / strength, η = η0 / rate^n (n = ${add.nc} / ${add.nt}), overstress capped at ${add.overc.toFixed(1)} MPa.`,
    });
  }
  return out;
}
