export function generate(input = {}) {
  const inp = { ...DEFAULTS, ...normalizeInput(input) };

  const mid  = mustIntPositive("mid", inp.mid);
  const ro   = mustPositive("ro", inp.ro);
  const E    = mustPositive("E", inp.E);
  const pr   = mustInRange("pr", inp.pr, 0.0, 0.49);
  const sigy = mustNonNeg("sigy", inp.sigy);
  const etan = mustNonNeg("etan", inp.etan);
  const beta = mustInRange("beta", inp.beta, 0.0, 1.0);

  // Optional Cowper–Symonds: blank/0 => write 0
  const src = readOptionalPositive(inp.src) ?? 0.0;
  const srp = readOptionalPositive(inp.srp) ?? 0.0;
  // FS = plastic strain at erosion; blank field -> LS-DYNA default 1E+20 (no erosion)
  const fs  = readOptionalPositive(inp.fs);
  const vp  = mustNonNegInt("vp", inp.vp);

  // ---- title (AUTO as you requested) ----
  // Manual (R13, MAT_003 Remark 2): BETA = 0 -> kinematic, BETA = 1 -> isotropic
  const hardeningText =
    beta <= 1e-12
      ? "kinematic hardening"
      : (Math.abs(beta - 1.0) <= 1e-12 ? "isotropic hardening" : `combined hardening (BETA=${toFixed(beta, 2)})`);

  const titleLine = `MAT_003 fy = ${toFixed(sigy, 1)} MPa, Etan = ${toFixed(etan, 1)} MPa, ${hardeningText}`;

  const lines = [];
  lines.push("$# LS-DYNA Keyword file created by LS-PrePost");
  lines.push("*KEYWORD");
  MATERIAL_CARDS_BANNER.forEach(s => lines.push(s));

  lines.push(UNITS_LINE);
  lines.push(MODEL_LINE);
  REF_LINES.forEach(s => lines.push(s));
  lines.push(HUB_LINE);

  lines.push("*MAT_PLASTIC_KINEMATIC_TITLE");
  lines.push(titleLine);

  lines.push("$#     MID        RO         E        PR      SIGY      ETAN      BETA");
  lines.push(
    `${fmt10(mid)}` +
    `${fmt10(ro, 7)}` +
    `${fmt10(E, 1)}` +
    `${fmt10(pr, 6)}` +
    `${fmt10(sigy, 6)}` +
    `${fmt10(etan, 6)}` +
    `${fmt10(beta, 6)}`
  );

  lines.push("$#     SRC       SRP        FS        VP");
  lines.push(
    `${fmt10(src, 6)}` +
    `${fmt10(srp, 6)}` +
    `${fs == null ? " ".repeat(10) : fmt10(fs, 6)}` +
    `${fmt10(vp)}`
  );

  lines.push("*END");
  lines.push("");

  const filename = `MAT_003_PLASTIC_KINEMATIC_mid=${mid}_fy=${toFixed(sigy, 1)}MPa.k`;
  return { filename, keyword: lines.join("\n") };
}

// ---- generic helpers (same style as your CDP file) ----
function normalizeInput(obj) {
  const out = { ...obj };
  for (const k of Object.keys(out)) if (out[k] === "") out[k] = "";
  return out;
}
function readOptionalNumber(x) {
  if (x === undefined || x === null) return null;
  const s = String(x).trim();
  if (s === "" || s === "0") return null;
  const v = Number(s);
  if (!Number.isFinite(v)) return null;
  if (v === 0) return null;
  return v;
}
function readOptionalPositive(x) {
  const v = readOptionalNumber(x);
  if (v == null) return null;
  if (v <= 0) return null;
  return v;
}
function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustNonNeg(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < 0) throw new Error(`${name} must be >= 0`);
  return v;
}
function mustNonNegInt(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi < 0) throw new Error(`${name} must be an integer >= 0`);
  return vi;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}
function toFixed(x, n) {
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x);
  return v.toFixed(n);
}
function fmt10(x, decimals = 6) {
  return fitW(fmt10Raw(x, decimals), x, 10);
}
function fmt10Raw(x, decimals = 6) {
  if (Number.isInteger(x)) return String(x).padStart(10, " ");
  const v = Number(x);
  if (!Number.isFinite(v)) return String(x).padStart(10, " ");
  const av = Math.abs(v);
  if (av !== 0 && (av >= 1e6 || av < 1e-4)) {
    return v.toExponential(3).replace("e", "E").padStart(10, " ");
  }
  return v.toFixed(decimals).padStart(10, " ");
}

// Never let a number overflow its field or touch the previous one (LS-DYNA reads by column).
function fitW(s, v, w) {
  const n = Number(v);
  if (!Number.isFinite(n)) return s;
  if (s.length > w || (s.length === w && s[0] !== " ")) return " " + fitField(n, w - 1);
  return s;
}

// ----------------------- figures (generator page) -----------------------
// Bilinear curve: sigma = E eps up to SIGY, then slope ETAN; FS marks element erosion
// (effective plastic strain, so total strain = sigma/E + FS). Cowper-Symonds yield scaling
// 1 + (rate/SRC)^(1/SRP) (LS-DYNA Keyword manual, *MAT_PLASTIC_KINEMATIC).
const logTick = v => Number.isInteger(v) ? `1e${v}` : Math.pow(10, v).toExponential(1);

export function figures(input = {}) {
  const E = Number(input.E), fy = Number(input.sigy), Et = Number(input.etan);
  if (!(E > 0) || !(fy >= 0) || !(Et >= 0)) return [];
  const fs = Number(input.fs), hasFs = String(input.fs ?? "").trim() !== "" && fs > 0;
  const ey = fy / E;
  const Ep = Et >= E ? 0 : E * Et / (E - Et);            // plastic modulus from the tangent modulus
  const epMax = hasFs ? fs * 1.15 : Math.max(0.10, 30 * ey);
  const pts = [[0, 0], [ey, fy]];
  for (let i = 1; i <= 40; i++) { const ep = epMax * i / 40; const s = fy + Ep * ep; pts.push([s / E + ep, s]); }
  const marks = [{ x: ey, y: fy, label: "SIGY", slot: 9 }];
  if (hasFs) { const s = fy + Ep * fs; marks.push({ x: s / E + fs, y: s, label: "FS (erosion)", slot: 4 }); }
  const out = [{
    title: "Stress–strain (uniaxial)", inputs: ["E", "sigy", "etan", "fs"],
    series: [{ label: "stress", slot: 1, points: pts, legend: false }],
    marks, xLabel: "strain (–)", yLabel: "stress (MPa)",
    caption: "Elastic to SIGY, then linear hardening with tangent modulus ETAN.",
  }];
  const C = Number(input.src), P = Number(input.srp);
  if (C > 0 && P > 0) {
    const ser = [];
    for (let i = 0; i <= 60; i++) { const lg = -5 + 9 * i / 60; const r = Math.pow(10, lg) / 1000;   // 1/s -> 1/ms
      ser.push([lg, 1 + Math.pow(r / C, 1 / P)]); }
    out.push({
      title: "Strain-rate scaling of SIGY", inputs: ["src", "srp"],
      series: [{ label: "Cowper–Symonds factor", slot: 2, points: ser }], xMin: -5, xMax: 4, yMin: 1,
      xTick: logTick, xLabel: "strain rate (1/s)", yLabel: "dynamic / static yield",
      caption: "1 + (rate / SRC)^(1/SRP), rate converted to 1/ms as SRC.",
    });
  }
  return out;
}
