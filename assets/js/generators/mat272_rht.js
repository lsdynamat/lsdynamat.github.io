// *MAT_RHT (MAT_272): Riedel-Hiermaier-Thoma concrete model with p-alpha compaction (solids).
// LS-DYNA generates every parameter from the compressive strength (ONEMPA < 0, manual remarks);
// the generator writes FC, the erosion strain and optional overrides, and lists what LS-DYNA will generate.
// Units: mm-ms-g-N-MPa

import { fitField } from "../core/units.js?v=20261022b";
export const KEY = "mat272_rht";
export const ID = 272;
export const NAME = "RHT Concrete (*MAT_RHT)";
export const CATEGORY = "Concrete";
export const UNITS = "mm-ms-g-N-MPa";

// ONEMPA is a unit-system code (-1 ... -7) when parameters are generated: "ONEMPA" maps it per system.
export const UNIT_SPEC = {
  "*MAT_RHT": { rows: [
    ["-", "D", "S", "ONEMPA", "-", "-", "-", "S"],
    ["-", "-", "S", "-", "-", "-", "-", "S"],
    ["R", "R", "R", "R", "-", "-", "-", "-"],
    ["-", "-", "-", "-", "-", "-", "-", "-"],
    ["-", "S", "S", "S", "S", "S", "-", "-"],
  ] },
};

const UNITS_LINE = "$ Units: mm-ms-g-N-MPa";
const HUB_LINE = "$ Generated by LS DYNA Material Hub https://lsdynamat.github.io/";
const REF_LINES = [
  "$ Model: RHT concrete - *MAT_RHT (MAT_272), solid elements",
  "$ Reference: LS-DYNA Keyword User's Manual Vol. II R13, *MAT_RHT (automatic generation, ONEMPA < 0)",
  "$ Reference: Grunwald et al. 2017, Int J Prot Struct 8(1):58-85, doi:10.1177/2041419617695977",
];

// Values LS-DYNA R13 generates (read from d3hsp for f_c = 20 ... 160 MPa): strength-independent ones,
// and the ones interpolated linearly in f_c between the 35 and 140 MPa sets of Riedel (2004).
const FIXED = { A: 1.60, N: 0.61, FS: 0.18, FT: 0.10, Q0: 0.6805, B: 0.0105, GC: 0.53, GT: 0.70, D1: 0.04, D2: 1.0 };
const lerp = (fc, a, b) => a + (fc - 35) * (b - a) / 105;

export function generate(input = {}) {
  const inp = normalizeInput(input);

  const mid = mustIntPositive("MID", inp.mid ?? 272);
  const fc = mustInRange("f_c", inp.fc ?? 48, 10, 200);
  const epsf = inp.epsf !== undefined ? mustPositive("EPSF", inp.epsf) : 2.0;
  const roIn = inp.ro !== undefined ? mustPositive("RO", inp.ro) : 0;

  // what LS-DYNA R13 generates (checked on d3hsp)
  const alpha0 = lerp(fc, 1.1884, 1.0913);
  const roGen = 2.75e-3 / alpha0;
  const G = lerp(fc, 16700, 22060);
  const pel = lerp(fc, 23.3, 93.3);

  const f = (v) => " " + fitField(v, 9);
  const i10 = (v) => String(Math.trunc(v)).padStart(10);

  const lines = [];
  lines.push("$# LS-DYNA Keyword file created by LS-PrePost");
  lines.push("*KEYWORD");
  lines.push("$ --+----1----+----2----+----3----+----4----+----5----+----6----+----7----+----8");
  lines.push("$                                                                              $");
  lines.push("$                                MATERIAL CARDS                                $");
  lines.push("$                                                                              $");
  lines.push("$ --+----1----+----2----+----3----+----4----+----5----+----6----+----7----+----8");
  lines.push("*MAT_RHT_TITLE");
  lines.push(`MAT_272 RHT fc=${fc.toFixed(1)}MPa`);
  lines.push(UNITS_LINE);
  REF_LINES.forEach(s => lines.push(s));
  lines.push(`$ ONEMPA < 0: LS-DYNA generates all zero fields for f_c = ${fc.toFixed(1)} MPa`);
  if (fc < 35 || fc > 140) {
    lines.push(`$ WARNING: f_c outside 35-140 MPa, the generated parameters are extrapolated`);
  }
  lines.push(`$ expected in d3hsp (R13): G = ${G.toFixed(0)} MPa, alpha0 = ${alpha0.toFixed(4)}, PEL = ${pel.toFixed(2)} MPa,`);
  lines.push(`$   RO = ${roGen.toExponential(4)} g/mm3 (= 2.75e-3 / alpha0), FT* = ${FIXED.FT} (f_t = ${(FIXED.FT * fc).toFixed(2)} MPa), FS* = ${FIXED.FS},`);
  lines.push(`$   A = ${FIXED.A}, N = ${FIXED.N}, Q0 = ${FIXED.Q0}, B = ${FIXED.B}, GC* = ${FIXED.GC}, GT* = ${FIXED.GT}, D1 = ${FIXED.D1}, D2 = ${FIXED.D2}`);
  lines.push(`$   strain rate: DIF = (rate / E0C)^BETAC, E0C = 3e-5 /s, BETAC = 1/(5 + 3 f_c/4) = ${(1 / (5 + 0.75 * fc)).toFixed(5)};`);
  lines.push(`$   tension E0T = 3e-6 /s, BETAT = 1/(10 + f_c/2) = ${(1 / (10 + 0.5 * fc)).toFixed(5)} (f_c in MPa)`);
  if (roIn > 0) lines.push(`$ RO overrides the generated density; ALPHA0 is still generated`);
  lines.push(`$ EPSF = ${epsf}: element erosion at this plastic strain (manual default 2.0)`);
  lines.push(HUB_LINE);

  lines.push("$#     mid        ro     shear    onempa      epsf        b0        b1        t1");
  lines.push(i10(mid) + f(roIn) + f(0) + f(-5) + f(epsf) + f(0) + f(0) + f(0));
  lines.push("$#       a         n        fc       fs*       ft*        q0         b        t2");
  lines.push(f(0) + f(0) + f(fc) + f(0) + f(0) + f(0) + f(0) + f(0));
  lines.push("$#     e0c       e0t        ec        et     betac     betat       ptf");
  lines.push(f(0) + f(0) + f(0) + f(0) + f(0) + f(0) + f(0));
  lines.push("$#     gc*       gt*        xi        d1        d2       epm        af        nf");
  lines.push(f(0) + f(0) + f(0) + f(0) + f(0) + f(0) + f(0) + f(0));
  lines.push("$#   gamma        a1        a2        a3       pel       pco        np    alpha0");
  lines.push(f(0) + f(0) + f(0) + f(0) + f(0) + f(0) + f(0) + f(0));
  lines.push("*END");
  return { filename: `${KEY}.k`, keyword: lines.join("\n") };
}

// ----------------------- helpers -----------------------
function normalizeInput(obj) {
  const out = { ...obj };
  for (const k of Object.keys(out)) if (out[k] === "" || out[k] === null) out[k] = undefined;
  return out;
}
function mustPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v <= 0) throw new Error(`${name} must be > 0`);
  return v;
}
function mustIntPositive(name, x) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  const vi = Math.trunc(v);
  if (vi <= 0) throw new Error(`${name} must be an integer > 0`);
  return vi;
}
function mustInRange(name, x, lo, hi) {
  const v = Number(x);
  if (!Number.isFinite(v)) throw new Error(`${name} must be a number`);
  if (v < lo || v > hi) throw new Error(`${name} must be in [${lo}, ${hi}]`);
  return v;
}

// ----------------------- figures (generator page) -----------------------
// Drawn from the parameters LS-DYNA generates for this f_c (FIXED, lerp above; AF, NF, PCO, NP, EPM,
// A1-A3 are the 35 MPa set of Borrvall & Riedel 2011 / Grunwald et al. 2017 Table 1, which the d3hsp
// table in the theory notes shows unchanged for other f_c).
// Equations: Borrvall & Riedel 2011 (failure, elastic and residual surfaces, Lode factor, failure strain,
// DIF), Grunwald et al. 2017 Eq. 26 (p-alpha). Fr = 1 (static).
const LATE = { AF: 1.60, NF: 0.61, PCO: 6000, NP: 3.0, EPM: 0.01, A1: 35270, A2: 39580, A3: 9040 };
const logTick = v => Number.isInteger(v) ? `1e${v}` : Math.pow(10, v).toExponential(1);

function rhtSurfaces(fc) {
  const { A, N, FS, FT, Q0, B, GC, GT, D1, D2 } = FIXED;
  const R3 = (c, Q) => (2 * (1 - Q * Q) * c + (2 * Q - 1) * Math.sqrt(4 * (1 - Q * Q) * c * c + 5 * Q * Q - 4 * Q)) /
    (4 * (1 - Q * Q) * c * c + (1 - 2 * Q) ** 2);
  const Q1 = R3(Math.cos(Math.PI / 6), Q0);                       // shear meridian factor at p* = 0
  const pt = Q0 * FS * FT / (3 * (Q1 * FT - Q0 * FS));             // tensile pressure limit p_t* (< 0)
  const Qp = p => Math.min(1, Q0 + B * p);
  const fail = p => {                                              // TXC failure surface sigma_f*(p*)
    if (p >= 1 / 3) return A * Math.pow(p - 1 / 3 + Math.pow(A, -1 / N), N);
    if (p >= 0) return FS / Q1 + 3 * p * (1 - FS / Q1);
    if (p >= pt) return FS / Q1 - 3 * p * (1 / Qp(p) - FS / (Q1 * FT));
    return 0;
  };
  const pel = lerp(fc, 23.3, 93.3) / fc, pu = GC / 3;
  const elastic = p => {
    const t = 3 * p;
    const Fe = t >= GC ? GC : t <= -GT * FT ? GT : GT + (GC - GT) * (t + GT * FT) / (GC + GT * FT);
    const Fc = p <= pu ? 1 : p >= pel ? 0 : Math.sqrt(1 - ((p - pu) / (pel - pu)) ** 2);
    const g = Fe * Fc;
    return g > 0 ? fail(p / g) * g : 0;
  };
  const resid = p => p >= 0 ? LATE.AF * Math.pow(p, LATE.NF) : 0;
  const shear = p => fail(p) * R3(Math.sqrt(3) / 2, Qp(p));
  const txe = p => fail(p) * Qp(p);
  const epsF = p => p < pt ? null : Math.max(LATE.EPM, D1 * Math.pow(p - pt, D2));
  return { fail, elastic, resid, shear, txe, epsF, pt, pel };
}

export function figures(input = {}) {
  const fc = Number(input.fc);
  if (!(fc >= 10 && fc <= 200)) return [];
  const S = rhtSurfaces(fc);
  const { FT } = FIXED;
  const P = (lo, hi, n, f) => { const o = []; for (let i = 0; i <= n; i++) { const p = lo + (hi - lo) * i / n; const y = f(p); if (y != null) o.push([p, y]); } return o; };
  const out = [];
  out.push({
    title: "Strength surfaces (meridians)", inputs: ["fc"],
    series: [
      { label: "failure, compressive meridian", slot: 1, points: P(S.pt, 3, 160, S.fail) },
      { label: "failure, tensile meridian", slot: 4, points: P(S.pt, 3, 160, S.txe), dash: true },
      { label: "elastic limit", slot: 2, points: P(S.pt, S.pel, 120, S.elastic) },
      { label: "residual", slot: 3, points: P(0, 3, 120, S.resid) },
    ],
    marks: [{ x: 1 / 3, y: 1, label: "f_c", slot: 9 }, { x: -FT / 3, y: FT, label: "f_t", slot: 9 }],
    xMin: Math.floor(S.pt * 10) / 10, xLabel: "pressure p / f_c", yLabel: "equivalent stress / f_c",
    caption: "Normalised by f_c. Elastic limit closes at the crush pressure PEL; Lode-angle factor from Q0 and B.",
  });
  // p-alpha compaction with the solid polynomial EOS (internal energy taken as zero)
  const a0 = lerp(fc, 1.1884, 1.0913), pel = lerp(fc, 23.3, 93.3), { PCO, NP, A1, A2, A3 } = LATE;
  const alpha = p => Math.max(1, Math.min(a0, 1 + (a0 - 1) * Math.pow(Math.max(0, (PCO - p) / (PCO - pel)), NP)));
  const eta = ps => { let lo = 0, hi = 1; for (let k = 0; k < 60; k++) { const m = (lo + hi) / 2; (A1 * m + A2 * m * m + A3 * m ** 3 < ps ? lo = m : hi = m); } return (lo + hi) / 2; };
  const hyd = [];
  for (let i = 0; i <= 120; i++) {
    const p = PCO * 1.15 * Math.pow(i / 120, 2);
    const a = alpha(p), e = eta(p * a);
    hyd.push([1 - a / ((1 + e) * a0), p]);
  }
  out.push({
    title: "Compaction (p–α) and equation of state", inputs: ["fc"],
    series: [{ label: "pressure", slot: 2, points: hyd, legend: false }],
    marks: [{ x: hyd.find(q => q[1] >= pel)?.[0] ?? 0, y: pel, label: "PEL", slot: 4 },
      { x: hyd.find(q => q[1] >= PCO)?.[0] ?? 0, y: PCO, label: "PCO", slot: 4 }],
    xLabel: "volumetric strain (–)", yLabel: "pressure (MPa)",
    caption: `Porosity α0 = ${a0.toFixed(4)} crushes between PEL = ${pel.toFixed(1)} MPa and PCO = ${PCO} MPa (NP = ${NP}).`,
  });
  out.push({
    title: "Plastic strain at failure", inputs: ["fc"],
    series: [{ label: "ε_p,failure", slot: 4, points: P(S.pt, 3, 120, S.epsF), legend: false }],
    xMin: Math.floor(S.pt * 10) / 10, xLabel: "pressure p / f_c", yLabel: "plastic strain (–)",
    caption: `D1 (p* − p_t*)^D2, at least EPM = ${LATE.EPM}. EPSF = ${input.epsf ?? 2} (erosion) is separate.`,
  });
  const bc = 1 / (5 + 0.75 * fc), bt = 1 / (10 + 0.5 * fc);
  const dif = (r, e0, b) => r <= e0 ? 1 : Math.pow(r / e0, b);
  const C = [], T = [];
  for (let i = 0; i <= 70; i++) { const lg = -5 + 8 * i / 70, r = 10 ** lg; C.push([lg, dif(r, 3e-5, bc)]); T.push([lg, dif(r, 3e-6, bt)]); }
  out.push({
    title: "Strain-rate enhancement", inputs: ["fc"],
    series: [{ label: "compression", slot: 2, points: C }, { label: "tension", slot: 4, points: T }],
    xMin: -5, xMax: 3, yMin: 1, xTick: logTick, xLabel: "strain rate (1/s)", yLabel: "DIF",
    caption: `(rate / E0)^β: compression E0 = 3e-5 /s, β = ${bc.toFixed(4)}; tension E0 = 3e-6 /s, β = ${bt.toFixed(4)}.`,
  });
  return out;
}
